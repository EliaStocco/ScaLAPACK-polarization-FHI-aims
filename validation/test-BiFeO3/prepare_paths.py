#!/usr/bin/env python3
"""Prepare continuous BiFeO3 polarization paths for Table 1 verification.

The endpoint geometries are copied from validation/BiFeO3, where the Table 1
calculations are stored.  Atoms in the polar endpoint are translated by lattice
vectors to their nearest periodic image before interpolation.  This preserves a
continuous structural path rather than interpolating an arbitrary wrapped
representation of the endpoint.

The script creates inputs only.  It never runs FHI-aims and it refuses to
overwrite an existing functional directory unless --force is supplied.
"""

from __future__ import annotations

import argparse
import itertools
import shutil
from dataclasses import dataclass
from pathlib import Path


Vector = tuple[float, float, float]
Cell = tuple[Vector, Vector, Vector]
FUNCTIONALS = ("LDA", "PBE", "PBEsol", "HSE06")


@dataclass(frozen=True)
class Atom:
    species: str
    position: Vector
    annotations: tuple[str, ...]


@dataclass(frozen=True)
class Geometry:
    cell: Cell
    atoms: tuple[Atom, ...]


def add(left: Vector, right: Vector) -> Vector:
    return tuple(a + b for a, b in zip(left, right))


def subtract(left: Vector, right: Vector) -> Vector:
    return tuple(a - b for a, b in zip(left, right))


def scale(factor: float, vector: Vector) -> Vector:
    return tuple(factor * value for value in vector)


def squared_norm(vector: Vector) -> float:
    return sum(value * value for value in vector)


def read_geometry(path: Path) -> Geometry:
    """Read the cell, atoms, and per-atom FHI-aims annotations."""
    cell: list[Vector] = []
    atoms: list[Atom] = []
    lines = path.read_text().splitlines()
    index = 0
    while index < len(lines):
        line = lines[index]
        fields = line.split()
        if fields[:1] == ["lattice_vector"]:
            cell.append(tuple(float(value) for value in fields[1:4]))
        if fields[:1] == ["atom"]:
            annotations: list[str] = []
            while index + 1 < len(lines):
                next_line = lines[index + 1]
                next_fields = next_line.split()
                if next_fields[:1] in (["atom"], ["lattice_vector"]) or not next_line.startswith((" ", "\t")):
                    break
                annotations.append(next_line)
                index += 1
            atoms.append(Atom(
                species=fields[4],
                position=tuple(float(value) for value in fields[1:4]),
                annotations=tuple(annotations),
            ))
        index += 1
    if len(cell) != 3:
        raise ValueError(f"Expected three lattice vectors in {path}")
    if not atoms:
        raise ValueError(f"No atoms found in {path}")
    return Geometry(cell=tuple(cell), atoms=tuple(atoms))


def nearest_image(initial: Vector, final: Vector, final_cell: Cell) -> Vector:
    """Return the periodic image of final nearest to initial in Cartesian space."""
    candidates = []
    for shifts in itertools.product(range(-1, 2), repeat=3):
        translation = tuple(
            sum(shifts[index] * final_cell[index][component] for index in range(3))
            for component in range(3)
        )
        candidate = add(final, translation)
        candidates.append((squared_norm(subtract(candidate, initial)), candidate))
    return min(candidates, key=lambda item: item[0])[1]


def interpolate(initial: Geometry, final: Geometry, fraction: float) -> Geometry:
    """Linearly interpolate cells and minimum-image Cartesian coordinates."""
    if len(initial.atoms) != len(final.atoms):
        raise ValueError("The endpoint geometries have different numbers of atoms")
    cell = tuple(
        add(scale(1.0 - fraction, initial_vector), scale(fraction, final_vector))
        for initial_vector, final_vector in zip(initial.cell, final.cell)
    )
    atoms = []
    for initial_atom, final_atom in zip(initial.atoms, final.atoms):
        if initial_atom.species != final_atom.species:
            raise ValueError("The endpoint geometries do not have matching atom order")
        if initial_atom.annotations != final_atom.annotations:
            raise ValueError("The endpoint geometries have incompatible atom annotations")
        continuous_final = nearest_image(
            initial_atom.position, final_atom.position, final.cell
        )
        position = add(
            scale(1.0 - fraction, initial_atom.position),
            scale(fraction, continuous_final),
        )
        atoms.append(Atom(initial_atom.species, position, initial_atom.annotations))
    return Geometry(cell=cell, atoms=tuple(atoms))


def write_geometry(path: Path, geometry: Geometry) -> None:
    lines = [
        "# Generated by prepare_paths.py from the Table 1 endpoint geometries.",
        "# Do not relax this structure: it is an image on the polarization path.",
        "",
    ]
    lines.extend(
        "lattice_vector " + " ".join(f"{value:.16f}" for value in vector)
        for vector in geometry.cell
    )
    for atom in geometry.atoms:
        lines.append(
            "atom "
            + " ".join(f"{value:.16f}" for value in atom.position)
            + f" {atom.species}"
        )
        lines.extend(atom.annotations)
    path.write_text("\n".join(lines) + "\n")


def write_extxyz(path: Path, geometries: list[Geometry]) -> None:
    frames = []
    for geometry in geometries:
        lattice = " ".join(str(value) for vector in geometry.cell for value in vector)
        frames.extend((
            str(len(geometry.atoms)),
            f'Lattice="{lattice}" Properties=species:S:1:pos:R:3 pbc="T T T"',
        ))
        frames.extend(
            f"{atom.species} " + " ".join(f"{value:.16f}" for value in atom.position)
            for atom in geometry.atoms
        )
    path.write_text("\n".join(frames) + "\n")


def prepare_functional(root: Path, functional: str, images: int, force: bool) -> None:
    source_root = root.parent / "BiFeO3"
    reference_dir = source_root / "BiFeO3_R-3c_AFM" / functional / "converge"
    polar_dir = source_root / "BiFeO3_R3c_AFM" / functional / "converge"
    reference = read_geometry(reference_dir / "geometry.in")
    polar = read_geometry(polar_dir / "geometry.in")
    destination = root / functional
    if destination.exists() and any(destination.iterdir()) and not force:
        raise FileExistsError(
            f"{destination} is not empty; use --force only to replace generated inputs"
        )
    if destination.exists() and force:
        shutil.rmtree(destination)
    geometries = [interpolate(reference, polar, index / (images - 1)) for index in range(images)]
    destination.mkdir(exist_ok=True)
    geometries_dir = destination / "geometries"
    geometries_dir.mkdir(parents=True)
    for index, geometry in enumerate(geometries):
        write_geometry(geometries_dir / f"geometry.n={index}.in", geometry)
    write_extxyz(destination / "path.extxyz", geometries)
    write_extxyz(destination / "R-3c.extxyz", [geometries[0]])
    write_extxyz(destination / "R3c.extxyz", [geometries[-1]])
    polarization_control = (
        source_root / "BiFeO3_R-3c_AFM" / functional / "scalapack" / "control.in"
    )
    control_text = polarization_control.read_text()
    control_text = control_text.replace("KS_method                    parallel", "KS_method                    serial")
    control_text = "\n".join(
        line for line in control_text.splitlines() if not line.startswith("elsi_restart")
    ) + "\n"
    (destination / "control.in").write_text(control_text)
    (destination / "results").mkdir()
    (destination / "README.md").write_text(
        f"# {functional} BiFeO3 polarization path\n\n"
        "Generated from the Table 1 endpoint geometries by `../prepare_paths.py`.\n"
        f"The ten images run from R-3c (`geometry.n=0.in`) to R3c (`geometry.n={images - 1}.in`).\n"
        "Place the FHI-aims output for image `n` in `results/aims.n=<n>.out`, then run "
        "`../extract_folded_polarization.py ..` from this directory.\n"
    )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--functionals",
        nargs="+",
        choices=FUNCTIONALS,
        default=("LDA", "PBE", "HSE06"),
        help="Functionals to prepare (default: the three missing paths).",
    )
    parser.add_argument(
        "--images", type=int, default=10,
        help="Number of endpoint-inclusive path images (default: 10).",
    )
    parser.add_argument(
        "--force", action="store_true",
        help="Replace an existing generated functional directory.",
    )
    args = parser.parse_args()
    if args.images < 2:
        raise SystemExit("At least two path images are required")
    root = Path(__file__).resolve().parent
    for functional in args.functionals:
        prepare_functional(root, functional, args.images, args.force)
        print(f"Prepared {functional} path with {args.images} images")


if __name__ == "__main__":
    main()
